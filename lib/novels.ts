export function isNovelKey(v: unknown): v is string {
  return typeof v === "string" && NOVEL_SETTINGS.some((n) => n.key === v);
}

/** 随机抽一部小说（每局开局由服务端抽定，作为本局的"天机"） */
export function pickNovel(): NovelSetting {
  return NOVEL_SETTINGS[Math.floor(Math.random() * NOVEL_SETTINGS.length)];
}

export function getNovelSetting(key: string): NovelSetting | null {
  return NOVEL_SETTINGS.find((n) => n.key === key) ?? null;
}

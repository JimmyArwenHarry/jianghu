/* ======================================================
 * 开局指令（身份 / 命格）—— 置顶，最高优先级
 * ====================================================== */

const ROLE_PREAMBLE = (label: string, emoji: string): string =>
  `【开局身份（最高优先级）】本局玩家是以「${emoji}${label}」之身踏入乱世的小人物。` +
  `所有剧情必须从这一身份出发：先写他在这一身份里的处境与困境，再写他踏入江湖的契机；` +
  `他的谈吐、见识、软肋与欲望，都要带着这一身份的影子。`;

const DESTINY_PREAMBLE = (destiny: string, reading?: string): string =>
  `【测字命格（最高优先级）】本局开局，玩家在算命先生处测字，测得命格为「${destiny}」。` +
  `先生判曰：${reading || "天机不可尽言。"}。` +
  `这条命格是玩家一生的伏笔，必须贯穿全局：剧情的走向、关键的抉择、最终的结局，都要与这条命格暗中呼应，` +
  `并在终局时点题回响。`;

/**
 * 构建金庸剧本的系统提示词：传入身份/命格时，把对应指令放在最前（压过基底设定），
 * 否则原样返回基底（向后兼容）。
 */
export function buildJinYongPrompt(
  role?: RoleKey,
  destiny?: string,
  reading?: string
): string {
  const head: string[] = [];
  if (role) {
    head.push(ROLE_PREAMBLE(roleLabel(role), roleEmoji(role)));
  }
  if (destiny) {
    head.push(DESTINY_PREAMBLE(destiny, reading));
  }
  if (head.length === 0) return JINYONG_SYSTEM_PROMPT;

  const tail = role
    ? `再次强调：本局玩家是以「${roleLabel(role)}」之身踏入江湖的卑微小人物，` +
      (destiny
        ? `测得命格「${destiny}」。从开局到终局，身份与命格必须始终如影随形。`
        : "从开局到终局，这一身份必须始终如影随形。")
    : `再次强调：本局命格「${destiny}」必须贯穿全局，终局点题。`;

  return `${head.join("\n\n")}\n\n${JINYONG_SYSTEM_PROMPT}\n\n${tail}`;
}
